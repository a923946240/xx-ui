import { afterEach, describe, it, expect, vi } from 'vitest';
import { fireEvent, screen, waitFor } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';

import RuleFormModal from '@/pages/xray/routing/RuleFormModal';
import { keys } from '@/api/queryKeys';
import { HttpUtil, Msg } from '@/utils';

import { chooseSelectOption, renderWithProviders } from './test-utils';

describe('RuleFormModal edit preserves unsurfaced fields', () => {
  afterEach(() => vi.restoreAllMocks());

  it('adds an explicit standby to an existing domain rule and removes it when cleared', () => {
    vi.spyOn(HttpUtil, 'get').mockResolvedValue(new Msg(true, '', []));
    const onConfirm = vi.fn();
    renderWithProviders(
      <RuleFormModal
        open
        rule={{ type: 'field', domain: ['domain:google.com'], outboundTag: 'A', ruleTag: 'search' }}
        inboundTags={[]}
        outboundTags={['', 'A', 'B']}
        balancerTags={['', 'pool']}
        onClose={vi.fn()}
        onConfirm={onConfirm}
      />,
    );
    const standby = screen.getByLabelText('Backup outbound');
    chooseSelectOption(standby.id, 'B');
    fireEvent.click(screen.getByRole('button', { name: 'Save Changes' }));
    expect(onConfirm.mock.lastCall?.[0]).toMatchObject({
      outboundTag: 'A',
      fallbackOutboundTag: 'B',
      domain: ['domain:google.com'],
      ruleTag: 'search',
    });
    expect(onConfirm.mock.lastCall?.[0]).not.toHaveProperty('balancerTag');
    chooseSelectOption(standby.id, 'None');
    fireEvent.click(screen.getByRole('button', { name: 'Save Changes' }));
    expect(onConfirm.mock.lastCall?.[0]).toMatchObject({
      outboundTag: 'A',
      domain: ['domain:google.com'],
    });
    expect(onConfirm.mock.lastCall?.[0]).not.toHaveProperty('fallbackOutboundTag');
  });

  it('refuses an imported rule with conflicting standby and balancer targets', () => {
    vi.spyOn(HttpUtil, 'get').mockResolvedValue(new Msg(true, '', []));
    const onConfirm = vi.fn();
    renderWithProviders(
      <RuleFormModal
        open
        rule={{
          type: 'field',
          domain: ['domain:google.com'],
          outboundTag: 'A',
          fallbackOutboundTag: 'B',
          balancerTag: 'pool',
        }}
        inboundTags={[]}
        outboundTags={['', 'A', 'B']}
        balancerTags={['', 'pool']}
        onClose={vi.fn()}
        onConfirm={onConfirm}
      />,
    );
    fireEvent.click(screen.getByRole('button', { name: 'Save Changes' }));
    expect(onConfirm).not.toHaveBeenCalled();
    expect(screen.getByText('Choose two different outbounds and clear the balancer.')).toBeTruthy();
    fireEvent.click(screen.getByRole('switch'));
    fireEvent.click(screen.getByRole('button', { name: 'Save Changes' }));
    expect(onConfirm.mock.lastCall?.[0]).toMatchObject({
      enabled: false,
      outboundTag: 'A',
      fallbackOutboundTag: 'B',
      balancerTag: 'pool',
    });
  });

  it('disables failover for a DNS allow rule regenerated by the panel on save', () => {
    vi.spyOn(HttpUtil, 'get').mockResolvedValue(new Msg(true, '', []));
    renderWithProviders(
      <RuleFormModal
        open
        rule={{ type: 'field', ruleTag: 'xui-dns-allow', outboundTag: 'direct' }}
        inboundTags={[]}
        outboundTags={['direct', 'B']}
        balancerTags={[]}
        onClose={vi.fn()}
        onConfirm={vi.fn()}
      />,
    );
    expect(screen.getByLabelText<HTMLInputElement>('Backup outbound').disabled).toBe(true);
  });

  it('keeps a client reverse tag available for plain routing only', () => {
    vi.spyOn(HttpUtil, 'get').mockResolvedValue(new Msg(true, '', []));
    const onConfirm = vi.fn();
    renderWithProviders(
      <RuleFormModal
        open
        rule={{ type: 'field', domain: ['domain:example.org'], outboundTag: 'A' }}
        inboundTags={[]}
        outboundTags={['', 'A', 'B']}
        clientReverseTags={['reverse-user']}
        balancerTags={[]}
        onClose={vi.fn()}
        onConfirm={onConfirm}
      />,
    );
    const standby = screen.getByLabelText<HTMLInputElement>('Backup outbound');
    chooseSelectOption(standby.id, 'B');
    expect(document.querySelector('.ant-select-item-option[title="reverse-user"]')).toBeNull();
    chooseSelectOption(screen.getByLabelText('Outbound tag').id, 'reverse-user');
    expect(standby.disabled).toBe(true);
    fireEvent.click(screen.getByRole('button', { name: 'Save Changes' }));
    expect(onConfirm.mock.lastCall?.[0]).toMatchObject({ outboundTag: 'reverse-user' });
    expect(onConfirm.mock.lastCall?.[0]).not.toHaveProperty('fallbackOutboundTag');
  });

  it('keeps a field the form does not surface (ruleTag) when saving an edit', () => {
    vi.spyOn(HttpUtil, 'get').mockResolvedValue(new Msg(true, '', []));
    const onConfirm = vi.fn();
    const queryClient = new QueryClient({ defaultOptions: { queries: { retry: false } } });

    renderWithProviders(
      <QueryClientProvider client={queryClient}>
        <RuleFormModal
          open
          rule={{ type: 'field', outboundTag: 'block', ruleTag: 'my-tag', enabled: true }}
          inboundTags={[]}
          outboundTags={['block']}
          balancerTags={[]}
          onClose={vi.fn()}
          onConfirm={onConfirm}
        />
      </QueryClientProvider>,
    );

    fireEvent.click(screen.getByRole('button', { name: 'Save Changes' }));

    expect(onConfirm).toHaveBeenCalledTimes(1);
    expect(onConfirm.mock.calls[0][0]).toMatchObject({ ruleTag: 'my-tag' });
  });

  it('selects existing clients for the user criterion', async () => {
    vi.spyOn(HttpUtil, 'get').mockResolvedValue(
      new Msg(true, '', [
        { id: 1, email: 'alice@example.com' },
        { id: 2, email: 'bob@example.com' },
      ]),
    );
    const onConfirm = vi.fn();
    const queryClient = new QueryClient({ defaultOptions: { queries: { retry: false } } });

    renderWithProviders(
      <RuleFormModal
        open
        rule={null}
        inboundTags={[]}
        outboundTags={['direct']}
        balancerTags={[]}
        onClose={vi.fn()}
        onConfirm={onConfirm}
      />,
      { queryClient },
    );

    await waitFor(() =>
      expect(HttpUtil.get).toHaveBeenCalledWith('/panel/api/clients/list', undefined, {
        silent: true,
      }),
    );
    await waitFor(() => expect(queryClient.getQueryData(keys.clients.all())).toHaveLength(2));
    const userField = screen.getByLabelText('User');
    expect(screen.getByText('Select users')).toBeTruthy();
    chooseSelectOption(userField.id, 'alice@example.com');
    chooseSelectOption(userField.id, 'bob@example.com');
    fireEvent.click(screen.getByRole('button', { name: 'Create' }));

    expect(onConfirm).toHaveBeenCalledWith(
      expect.objectContaining({ user: ['alice@example.com', 'bob@example.com'] }),
    );
  });

  it('preserves a saved user that is no longer in the client list', async () => {
    vi.spyOn(HttpUtil, 'get').mockResolvedValue(
      new Msg(true, '', [{ id: 1, email: 'alice@example.com' }]),
    );
    const onConfirm = vi.fn();

    renderWithProviders(
      <RuleFormModal
        open
        rule={{ type: 'field', user: ['removed@example.com'], outboundTag: 'direct' }}
        inboundTags={[]}
        outboundTags={['direct']}
        balancerTags={[]}
        onClose={vi.fn()}
        onConfirm={onConfirm}
      />,
    );

    await waitFor(() => expect(screen.getByText('removed@example.com')).toBeTruthy());
    fireEvent.click(screen.getByRole('button', { name: 'Save Changes' }));

    expect(onConfirm).toHaveBeenCalledWith(
      expect.objectContaining({ user: ['removed@example.com'] }),
    );
  });

  it('accepts a custom user identifier that is not a client record', async () => {
    vi.spyOn(HttpUtil, 'get').mockResolvedValue(
      new Msg(true, '', [{ id: 1, email: 'alice@example.com' }]),
    );
    const onConfirm = vi.fn();

    renderWithProviders(
      <RuleFormModal
        open
        rule={null}
        inboundTags={[]}
        outboundTags={['direct']}
        balancerTags={[]}
        onClose={vi.fn()}
        onConfirm={onConfirm}
      />,
    );

    const userField = screen.getByLabelText('User');
    fireEvent.change(userField, { target: { value: 'office-proxy,' } });
    fireEvent.click(screen.getByRole('button', { name: 'Create' }));

    expect(onConfirm).toHaveBeenCalledWith(expect.objectContaining({ user: ['office-proxy'] }));
  });
});
