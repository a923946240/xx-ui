const (
	natSyncReadCommand  = "xx-ui-nat-read"
	natSyncReportLimit  = 512
	natSyncMaxReportAge = 60
)

var (
	natSyncRelayUser         = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_.-]{0,63}$`)
	errNATSyncHostKey        = errors.New("SSH relay host key does not match the configured fingerprint")
	errNATSyncNoKey          = errors.New("generate a NAT sync reader key first")
	errNATSyncBlockedAddress = errors.New("SSH relay resolved to a blocked address")

	// Amazon reserves this private IPv6 range for instance-local services, including IMDS.
	natSyncEC2Local = netip.MustParsePrefix("fd00:ec2::/32")
)

func validateNATSyncRelay(cfg NATSyncConfig) error {
	if _, err := netsafe.NormalizeHost(cfg.RelayHost); err != nil ||
		strings.TrimSpace(cfg.RelayHost) != cfg.RelayHost {
		return errors.New("enter a valid SSH relay host")
	}
	if cfg.RelayPort < 1 || cfg.RelayPort > 65535 {
		return errors.New("enter a valid SSH relay port")
	}
	if !natSyncRelayUser.MatchString(cfg.RelayUser) {
		return errors.New("enter a valid SSH relay user")
	}
	encoded, ok := strings.CutPrefix(cfg.HostKeyFingerprint, "SHA256:")
	hash, err := base64.RawStdEncoding.Strict().DecodeString(encoded)
	if !ok || err != nil || len(hash) != 32 || base64.RawStdEncoding.EncodeToString(hash) != encoded {
		return errors.New("enter the SHA256 fingerprint of the relay's Ed25519 SSH host key")
	}
	return nil
}

func natSyncPublicKey(create bool) (string, error) {
	signer, err := natSyncReaderKey(create)
	if err != nil || signer == nil {
		return "", err
	}
	return strings.TrimSpace(string(ssh.MarshalAuthorizedKey(signer.PublicKey()))), nil
}

func natSyncReaderKey(create bool) (ssh.Signer, error) {
	root := config.GetDBFolderPath()
	if create {
		// External databases do not necessarily create the local database directory.
		if err := os.MkdirAll(root, 0o700); err != nil {
			return nil, errors.New("cannot create the private NAT sync key directory")
		}
	}
	dir := filepath.Join(root, "nat-ssh-keys")
	if err := secureNATSyncDirectory(dir, create); err != nil {
		if !create && errors.Is(err, os.ErrNotExist) {
			return nil, nil
		}
		return nil, errors.New("cannot open the private NAT sync key directory")
	}
	path := filepath.Join(dir, "reader-key")
	signer, err := loadNATSyncKey(path)
	if !errors.Is(err, os.ErrNotExist) {
		return signer, err
	}
	if !create {
		return nil, nil
	}
	if err := generateNATSyncKey(dir, path); err != nil {
		return nil, errors.New("cannot generate the NAT sync reader key")
	}
	return loadNATSyncKey(path)
}

func loadNATSyncKey(path string) (ssh.Signer, error) {
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, err
	}
	if err != nil || !info.Mode().IsRegular() || info.Size() > 4096 ||
		checkNATSyncKeyPermissions(path, info) != nil {
		return nil, errors.New("cannot read the private NAT sync reader key")
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, errors.New("cannot read the private NAT sync reader key")
	}
	signer, err := ssh.ParsePrivateKey(data)
	if err != nil || signer.PublicKey().Type() != ssh.KeyAlgoED25519 {
		return nil, errors.New("invalid NAT sync reader key")
	}
	return signer, nil
}

func generateNATSyncKey(dir, path string) error {
	_, privateKey, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return err
	}
	block, err := ssh.MarshalPrivateKey(privateKey, "xx-ui NAT sync reader")
	if err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, ".reader-key-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	writeErr := protectNATSyncTempKey(tmp.Name())
	if writeErr == nil {
		writeErr = pem.Encode(tmp, block)
	}
	if writeErr == nil {
		writeErr = tmp.Sync()
	}
	closeErr := tmp.Close()
	if err := errors.Join(writeErr, closeErr); err != nil {
		return err
	}
	// Publish the whole file without replacing a key generated by another request.
	if err := os.Link(tmp.Name(), path); err != nil && !errors.Is(err, os.ErrExist) {
		return err
	}
	return nil
}

func natSyncHostKeyCallback(fingerprint string) ssh.HostKeyCallback {
	return func(_ string, _ net.Addr, key ssh.PublicKey) error {
		if key.Type() != ssh.KeyAlgoED25519 || ssh.FingerprintSHA256(key) != fingerprint {
			return errNATSyncHostKey
		}
		return nil
	}
}

func guardNATSyncRelayDial(_ context.Context, _ string, endpoint string, _ syscall.RawConn) error {
	addrPort, err := netip.ParseAddrPort(endpoint)
	if err != nil {
		return errors.New("invalid SSH relay address")
	}
	addr := addrPort.Addr().Unmap()
	// A relay on a private management network is permitted. Loopback, link-local,
	// carrier NAT and IPv6 transition prefixes cannot be used to reach local services.
	if !addr.IsGlobalUnicast() || natSyncEC2Local.Contains(addr) ||
		(!addr.IsPrivate() && netsafe.IsBlockedIP(net.IP(addr.AsSlice()))) {
		return errNATSyncBlockedAddress
	}
	return nil
}

func readNATSyncRelay(ctx context.Context, cfg NATSyncConfig) (NATSyncReport, error) {
	if err := validateNATSyncRelay(cfg); err != nil {
		return NATSyncReport{}, err
	}
	signer, err := natSyncReaderKey(false)
	if err != nil {
		return NATSyncReport{}, err
	}
	if signer == nil {
		return NATSyncReport{}, errNATSyncNoKey
	}
	host, _ := netsafe.NormalizeHost(cfg.RelayHost)
	endpoint := net.JoinHostPort(host, strconv.Itoa(cfg.RelayPort))
	ctx, cancel := context.WithTimeout(ctx, 8*time.Second)
	defer cancel()
	dialer := net.Dialer{Timeout: 4 * time.Second, ControlContext: guardNATSyncRelayDial}
	conn, err := dialer.DialContext(ctx, "tcp", endpoint)
	if err != nil {
		if errors.Is(err, errNATSyncBlockedAddress) {
			return NATSyncReport{}, errNATSyncBlockedAddress
		}
		return NATSyncReport{}, errors.New("cannot connect to SSH relay; check its address, port and firewall")
	}
	defer conn.Close()
	deadline, _ := ctx.Deadline()
	if err := conn.SetDeadline(deadline); err != nil {
		return NATSyncReport{}, errors.New("cannot set SSH relay deadline")
	}
	stop := context.AfterFunc(ctx, func() { _ = conn.Close() })
	defer stop()

	return readNATSyncSSHSession(conn, endpoint, cfg, signer)
}

func readNATSyncSSHSession(conn net.Conn, endpoint string, cfg NATSyncConfig, signer ssh.Signer) (NATSyncReport, error) {
	config := &ssh.ClientConfig{
		User:              cfg.RelayUser,
		Auth:              []ssh.AuthMethod{ssh.PublicKeys(signer)},
		HostKeyCallback:   natSyncHostKeyCallback(cfg.HostKeyFingerprint),
		HostKeyAlgorithms: []string{ssh.KeyAlgoED25519},
	}
	connection, channels, requests, err := ssh.NewClientConn(conn, endpoint, config)
	if err != nil {
		if errors.Is(err, errNATSyncHostKey) {
			return NATSyncReport{}, errNATSyncHostKey
		}
		return NATSyncReport{}, errors.New("SSH relay handshake or authentication failed; check its Ed25519 host key, user and authorized reader key")
	}
	client := ssh.NewClient(connection, channels, requests)
	defer client.Close()
	session, err := client.NewSession()
	if err != nil {
		return NATSyncReport{}, errors.New("cannot open the SSH relay read session")
	}
	defer session.Close()
	var result natSyncReportBuffer
	session.Stdout = &result
	session.Stderr = io.Discard
	if err := session.Run(natSyncReadCommand); err != nil {
		return NATSyncReport{}, errors.New("SSH relay report read failed; check the restricted read command and the latest NAT report")
	}
	return parseNATSyncRelayReport(result.buffer.Bytes(), time.Now())
}

type natSyncReportBuffer struct{ buffer bytes.Buffer }

func (b *natSyncReportBuffer) Write(p []byte) (int, error) {
	if len(p) > natSyncReportLimit-b.buffer.Len() {
		return 0, errors.New("SSH relay report is too large")
	}
	return b.buffer.Write(p)
}

func parseNATSyncRelayReport(body []byte, now time.Time) (NATSyncReport, error) {
	body = bytes.TrimSpace(body)
	report := NATSyncReport{CandidateIP: string(body)}
	if len(body) > 0 && body[0] == '{' {
		var payload struct {
			Address string  `json:"address"`
			SeenAt  float64 `json:"seen_at"`
		}
		if err := json.Unmarshal(body, &payload); err != nil {
			return NATSyncReport{}, errors.New("invalid JSON received from the SSH relay")
		}
		age := float64(now.Unix()) + float64(now.Nanosecond())/1e9 - payload.SeenAt
		if payload.SeenAt <= 0 || age < 0 || age > natSyncMaxReportAge {
			return NATSyncReport{}, errors.New("NAT report is missing, expired or ahead of the panel clock")
		}
		report.CandidateIP, report.SeenAt = payload.Address, int64(payload.SeenAt)
	}
	// Old forced commands return a plain IP after checking report age on the relay.
	addr, err := netip.ParseAddr(report.CandidateIP)
	if err != nil || !natSyncPublicIPv4(addr) {
		return NATSyncReport{}, errors.New("SSH relay did not report a public IPv4 address")
	}
	report.CandidateIP = addr.String()
	return report, nil
}

// Special-purpose IPv4 ranges rejected by the relay script's public IP check.
var natSyncNonPublic = [...]netip.Prefix{
	netip.MustParsePrefix("0.0.0.0/8"),
	netip.MustParsePrefix("192.0.0.0/24"),
	netip.MustParsePrefix("192.0.2.0/24"),
	netip.MustParsePrefix("198.18.0.0/15"),
	netip.MustParsePrefix("198.51.100.0/24"),
	netip.MustParsePrefix("203.0.113.0/24"),
	netip.MustParsePrefix("240.0.0.0/4"),
}

func natSyncPublicIPv4(addr netip.Addr) bool {
	if !addr.Is4() || !addr.IsGlobalUnicast() || netsafe.IsBlockedIP(net.IP(addr.AsSlice())) {
		return false
	}
	if addr == netip.AddrFrom4([4]byte{192, 0, 0, 9}) || addr == netip.AddrFrom4([4]byte{192, 0, 0, 10}) {
		return true
	}
	for _, prefix := range natSyncNonPublic {
		if prefix.Contains(addr) {
			return false
		}
	}
	return true
}
